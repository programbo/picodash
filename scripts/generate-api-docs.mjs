import { createHash } from 'node:crypto'
import { readFile, readdir, mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'docs/reference/api')
const packages = ['nexus', 'ui', 'dashpanel', 'dashstack', 'picodash', 'dev-bridge']
const check = process.argv.includes('--check')
const generated = new Map()
const sources = {}
async function files(directory) {
  const results = []
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) results.push(...(await files(file)))
    else results.push(file)
  }
  return results.sort((a, b) => a.localeCompare(b))
}
for (const name of packages) {
  const packageRoot = path.join(root, 'packages', name)
  const manifest = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'))
  const digest = createHash('sha256')
  for (const file of [
    path.join(packageRoot, 'package.json'),
    ...(await files(path.join(packageRoot, 'src'))),
  ]) {
    if (/\.(?:test|spec)\.[cm]?[jt]sx?$/.test(file)) continue
    digest
      .update(path.relative(root, file))
      .update('\0')
      .update(await readFile(file))
      .update('\0')
  }
  sources[name] = digest.digest('hex')
  let page = `# ${manifest.name}: public exports\n\nGenerated by \`bun run docs:generate\` from the package manifest and emitted declarations.\nRuntime names are verified against the built JavaScript module; other declared names are type-only and erased. Supporting declaration types do not create public exports.\n\n`
  const declarationFiles = (await files(path.join(packageRoot, 'dist'))).filter((file) =>
    file.endsWith('.d.mts'),
  )
  for (const file of declarationFiles)
    generated.set(`declarations/${name}/${path.basename(file)}.txt`, await readFile(file, 'utf8'))
  for (const [subpath, descriptor] of Object.entries(manifest.exports)) {
    const target = typeof descriptor === 'string' ? descriptor : descriptor.import
    if (typeof target !== 'string')
      throw new Error(`${manifest.name}: unsupported export descriptor; update generator`)
    const specifier = manifest.name + (subpath === '.' ? '' : subpath.slice(1))
    page += `## ${specifier}\n\nManifest target: \`${target}\`.\n\n`
    if (!target.endsWith('.mjs')) {
      page += target.endsWith('.css')
        ? 'Stylesheet entrypoint; no JavaScript names.\n\n'
        : 'Package metadata entrypoint.\n\n'
      continue
    }
    const declaration = target.replace(/\.mjs$/, '.d.mts')
    const contents = await readFile(path.join(packageRoot, declaration), 'utf8')
    const listed = [
      ...contents.matchAll(/export\s+(type\s+)?\{([^}]+)\}(?:\s*from\s*[^;]+)?;/g),
    ].flatMap((match) =>
      match[2]
        .split(',')
        .map((item) => item.trim())
        .filter(Boolean)
        .map((entry) => (match[1] && !entry.startsWith('type ') ? `type ${entry}` : entry)),
    )
    const direct = [
      ...contents.matchAll(
        /export\s+(?:declare\s+)?(function|class|const|let|var|interface|type|enum)\s+([\w$]+)/g,
      ),
    ].map(([, kind, name]) => (kind === 'type' || kind === 'interface' ? 'type ' : '') + name)
    const exports = [...new Set([...listed, ...direct])]
    const runtimeValues = Object.keys(
      await import(pathToFileURL(path.join(packageRoot, target)).href),
    )
    const declaredNames = new Set(
      exports.map((entry) =>
        entry
          .replace(/^type /, '')
          .split(/\s+as\s+/)
          .at(-1),
      ),
    )
    const missing = runtimeValues.filter((name) => !declaredNames.has(name))
    if (missing.length)
      throw new Error(
        `${specifier}: runtime exports missing from declarations: ${missing.join(', ')}`,
      )
    if (!exports.length && !/cli/.test(subpath))
      throw new Error(`${specifier}: no declaration export list found`)
    page += `[Entrypoint declarations](declarations/${name}/${path.basename(declaration)}.txt). Local declaration imports resolve through the supporting files listed below.\n\n| Name | Kind |\n| --- | --- |\n`
    for (const entry of exports.sort((a, b) =>
      a.replace(/^type /, '').localeCompare(b.replace(/^type /, '')),
    )) {
      const publicName = entry
        .replace(/^type /, '')
        .split(/\s+as\s+/)
        .at(-1)
      page += `| \`${publicName}\` | ${runtimeValues.includes(publicName) ? 'Runtime' : 'Type'} |\n`
    }
    page += '\n'
  }
  if (manifest.bin)
    page += `## Executables\n\n${Object.entries(manifest.bin)
      .map(([name, target]) => `- \`${name}\`: \`${target}\``)
      .join('\n')}\n\n`
  page += `## Supporting declarations\n\nThese are exact compiler-emitted declarations, including types needed to describe public signatures. They are stored as text to avoid creating another compilable package.\n\n${declarationFiles.map((file) => `- [${path.basename(file)}](declarations/${name}/${path.basename(file)}.txt)`).join('\n')}\n`
  generated.set(`${name}.md`, page)
}
generated.set(
  'index.md',
  '# Public API inventory\n\nGenerated from package manifests and built TypeScript declarations. Each page lists every exported JavaScript value, type-only name, stylesheet, metadata entrypoint and executable. Full signatures and dependent types are linked from each page.\n\n' +
    packages.map((name) => `- [@picodash/${name}](${name}.md)`).join('\n') +
    '\n\nBehavior and limitations live in the [owning references](../../index.md). Run `bun run docs:generate` after building a public source change; `bun run docs:check` detects stale source fingerprints and inventory output.\n',
)
generated.set('source-fingerprints.json', JSON.stringify(sources, null, 2) + '\n')
if (check) {
  const failures = []
  for (const [name, contents] of generated)
    if ((await readFile(path.join(output, name), 'utf8').catch(() => null)) !== contents)
      failures.push(name)
  const expected = [...generated.keys()].sort((a, b) => a.localeCompare(b))
  const actual = (await files(output))
    .map((file) => path.relative(output, file))
    .sort((a, b) => a.localeCompare(b))
  if (JSON.stringify(expected) !== JSON.stringify(actual)) failures.push('file inventory')
  if (failures.length)
    throw new Error(
      `API documentation is stale: ${failures.join(', ')}. Build packages and run bun run docs:generate.`,
    )
  console.log(`API documentation matches ${packages.length} packages and ${generated.size} files.`)
} else {
  await rm(output, { recursive: true, force: true })
  for (const [name, contents] of generated) {
    const file = path.join(output, name)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, contents)
  }
  console.log(`Generated ${generated.size} API files for ${packages.length} packages.`)
}
